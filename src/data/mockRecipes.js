/** Ингредиент из справочника: количество в удобной единице, граммы считаются сами. name можно переопределить. */
const ing = (productId, qty, unit, { name } = {}) => {
  const product = getProduct(productId);
  const grams = toGrams(product, qty, unit);
  return {
    productId: product ? productId : null,
    name: name ?? product?.name ?? productId,
    qty,
    unit,
    grams: grams === null ? 0 : Math.round(grams * 10) / 10,
    amountText: formatQtyUnit(qty, unit),
    scalable: unit !== 'taste',
  };
};
const toTaste = (name, productId = 'salt') => ing(productId, 0, 'taste', { name });
/** Продукта нет в справочнике — калорийность рецепта не считается. */
const custom = (name, qty, unit, grams) => ({ productId: null, name, qty, unit, grams, amountText: formatQtyUnit(qty, unit), scalable: true });
const step = (text, timerSeconds = 0, photoUrl = '') => ({ text, timerSeconds, photoUrl });

